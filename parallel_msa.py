#: Name of the shared DTALite working folder (relative to the repo root).
SOURCE_DIR = "DTALite_Files"
#: Data directory per network. Baltimore data lives in baltimore_files/
#: (generated by baltimore/build_baltimore_inputs.py); Sioux Falls uses
#: the repo's DTALite_Files/.
NETWORK_SOURCE_DIRS = {
    "siouxfalls": "DTALite_Files",
    "baltimore": "baltimore_files",
}

#: Sandbox folders are named ``Run0``, ``Run1``, ... under the repo root.
SANDBOX_PREFIX = "Run"

#: Files written by the pipeline that carry no per-iteration tag.  In the
#: serial runner the final on-disk state of these is whatever the *last*
#: iteration wrote, so the parallel orchestrator reproduces that by copying
#: them back from the highest ``bigloop`` run only.
SHARED_RESULT_NAMES = [
    "UOinfor_agent.csv",
    "UOinfor_LinkMOE.csv",
    "UOinfor_LinkTDMOE.csv",
]

# A single bigloop that produces no result within this long is treated
# as hung: fail with a clear error instead of blocking forever (which
# used to hang runner_parallel.py -- and therefore wholerunner --
# indefinitely at 100%%).
BIGLOOP_TIMEOUT_S = 3600

#: Per-bigloop wall-clock budget, measured from batch submission. A bigloop
#: still pending after this long is killed and marked failed (then retried
#: once) instead of holding the whole sweep hostage. Normal bigloops take
#: ~40-45 min; this gives a comfortable margin. A dynamic timeout (2x the
#: median peer duration, once >=3 bigloops finish) can fire earlier.
PER_BIGLOOP_TIMEOUT_S = 3000

#: Worker self-watchdog. A daemon thread inside each pool worker calls
#: os._exit(2) if the worker is still alive after this long. This converts
#: ANY worker-side hang (infinite loop, deadlocked I/O, stuck teardown --
#: e.g. the observed "20/20 done but never returned" hang) into a loud
#: failure the parent sees as BrokenProcessPoolError, instead of hanging
#: the sweep. Must exceed PER_BIGLOOP_TIMEOUT_S so the parent's orderly
#: per-bigloop timeout normally fires first; this is the backstop for when
#: the parent itself cannot act.
WORKER_WATCHDOG_S = 3300

#: How many times a failed/timed-out bigloop is retried with a fresh worker
#: pool before being recorded as a permanent failure.
MAX_RETRIES = 1



def _result_names(bigloop):
    """Per-iteration result files produced for a given ``bigloop``."""
    i = bigloop
    return [
        f"{i}UOinfor_agent.csv",
        f"{i}UOinfor_LinkMOE.csv",
        f"{i}UOinfor_LinkTDMOE.csv",
        f"{i}predict_agent.csv",
        f"{i}predict_LinkMOE.csv",
        f"{i}predict_LinkTDMOE.csv",
        f"{i}actual_agent.csv",
        f"{i}actual_LinkMOE.csv",
        f"{i}actual_LinkTDMOE.csv",
        f"myfile{i}.mat",
        f"pathinfo_ass{i}.mat",
        f"pathinfo_comass{i}.mat",
        f"pathinfo_comrealass{i}.mat",
        f"pathinfo_realass{i}.mat",
    ]


